import { StrictMode, useEffect, useMemo, useRef, useState, type ChangeEvent } from 'react'
import { createRoot } from 'react-dom/client'
import { Canvas, useThree } from '@react-three/fiber'
import { OrbitControls } from '@react-three/drei'
import * as THREE from 'three'
import { OBJLoader } from 'three/addons/loaders/OBJLoader.js'
import './style.css'

type LoadedMesh = { name: string; object: THREE.Group; bounds: THREE.Box3 }

function disposeObject(object: THREE.Object3D) {
  object.traverse((child) => {
    if (
      child instanceof THREE.Mesh ||
      child instanceof THREE.Line ||
      child instanceof THREE.Points
    ) {
      child.geometry.dispose()
      const materials = Array.isArray(child.material) ? child.material : [child.material]
      materials.forEach((material) => {
        material.dispose()
      })
    }
  })
}

function parseMesh(name: string, text: string): LoadedMesh {
  const object = new OBJLoader().parse(text)
  try {
    let meshCount = 0
    object.traverse((child) => {
      if (child instanceof THREE.Mesh) {
        meshCount++
        const materials = Array.isArray(child.material) ? child.material : [child.material]
        materials.forEach((material) => {
          material.dispose()
        })
        child.material = new THREE.MeshStandardMaterial({
          color: '#a990ec',
          roughness: 0.68,
          metalness: 0.05,
          side: THREE.DoubleSide,
        })
      }
    })
    const bounds = new THREE.Box3().setFromObject(object)
    if (!meshCount || bounds.isEmpty())
      throw new Error('No renderable faces were found in this OBJ file.')
    return { name, object, bounds }
  } catch (error) {
    disposeObject(object)
    throw error
  }
}

function Model({ model }: { model: LoadedMesh }) {
  const { camera, invalidate } = useThree()
  const center = useMemo(() => model.bounds.getCenter(new THREE.Vector3()), [model])
  useEffect(() => {
    const size = model.bounds.getSize(new THREE.Vector3())
    const extent = Math.max(size.x, size.y, size.z, 1)
    camera.position.copy(center).add(new THREE.Vector3(-extent * 1.3, -extent * 1.7, extent * 1.2))
    if (camera instanceof THREE.PerspectiveCamera) {
      camera.near = Math.max(extent / 10000, 0.001)
      camera.far = extent * 1000
      camera.updateProjectionMatrix()
    }
    invalidate()
  }, [camera, center, invalidate, model])
  return (
    <>
      <primitive object={model.object} dispose={null} />
      <OrbitControls makeDefault target={center} />
    </>
  )
}

function Viewport({ model }: { model: LoadedMesh | null }) {
  return (
    <section className="viewport" aria-label="3D mesh viewport">
      <Canvas
        frameloop="demand"
        dpr={[1, 2]}
        camera={{ position: [45, -60, 45], up: [0, 0, 1], fov: 45, near: 0.01, far: 100000 }}
      >
        <color attach="background" args={['#151a22']} />
        <hemisphereLight args={[0xf6f1ff, 0x303644, 2]} />
        <directionalLight position={[25, -40, 70]} intensity={2} />
        <gridHelper args={[200, 20, 0x667080, 0x313945]} rotation={[Math.PI / 2, 0, 0]} />
        <axesHelper args={[15]} />
        {model ? <Model model={model} /> : <OrbitControls makeDefault />}
      </Canvas>
    </section>
  )
}

function App() {
  const [model, setModel] = useState<LoadedMesh | null>(null)
  const [status, setStatus] = useState('Open an OBJ mesh generated by the CLI to begin.')
  const revision = useRef(0)
  useEffect(() => {
    let stopped = false
    let timer: ReturnType<typeof setTimeout> | undefined
    const controller = new AbortController()
    async function poll() {
      let shouldContinue = true
      try {
        const response = await fetch('/api/preview', {
          cache: 'no-store',
          signal: controller.signal,
        })
        if (!response.ok || !response.headers.get('content-type')?.includes('application/json')) {
          shouldContinue = false
          return
        }
        const data: {
          revision: number
          name: string
          mesh: string | null
          error: string | null
          building: boolean
        } = await response.json()
        if (stopped) return
        if (data.mesh && data.revision !== revision.current) {
          const loaded = parseMesh(data.name, data.mesh)
          setModel(loaded)
          revision.current = data.revision
        }
        if (data.error) setStatus(`Rebuild failed: ${data.error}`)
        else if (data.building) setStatus(`Rebuilding ${data.name}…`)
        else if (data.mesh) setStatus(`${data.name} · live preview`)
      } catch (error) {
        if (!stopped)
          setStatus(
            error instanceof Error
              ? `Preview unavailable: ${error.message}`
              : 'Preview unavailable.',
          )
      } finally {
        if (!stopped && shouldContinue) timer = setTimeout(poll, 1000)
      }
    }
    void poll()
    return () => {
      stopped = true
      controller.abort()
      if (timer) clearTimeout(timer)
    }
  }, [])
  useEffect(
    () => () => {
      if (model) disposeObject(model.object)
    },
    [model],
  )
  async function openFile(event: ChangeEvent<HTMLInputElement>) {
    const file = event.target.files?.[0]
    if (!file) return
    event.target.value = ''
    try {
      const loaded = parseMesh(file.name, await file.text())
      setModel(loaded)
      setStatus(`${loaded.name} · display mesh loaded`)
    } catch (error) {
      setStatus(error instanceof Error ? error.message : 'Could not read the selected file.')
    }
  }
  return (
    <main>
      <header>
        <div>
          <strong>solidrecipe</strong>
          <span className="tag">viewer prototype</span>
        </div>
        <label className="button">
          Open OBJ
          <input type="file" accept=".obj" onChange={openFile} />
        </label>
      </header>
      <section className="workspace">
        <Viewport model={model} />
        {!model && (
          <div className="empty">
            Open a model to inspect it.
            <small>Generate an OBJ with the solidrecipe CLI, then open it here.</small>
          </div>
        )}
      </section>
      <footer>
        <span role="status">{status}</span>
        <span>Orbit: drag · Pan: right-drag · Zoom: scroll</span>
        <span>Mesh preview · measurements unavailable</span>
      </footer>
    </main>
  )
}

const root = document.getElementById('root')
if (!root) throw new Error('Missing root element')
createRoot(root).render(
  <StrictMode>
    <App />
  </StrictMode>,
)
